// TestTheApplicationIntegrationHasOneCompositionFile keeps the package's
// installation surface as explicit as its constructor. A package is composed
// in bootstrap/app.go; another bootstrap file would be another place a reader
// has to search to learn what the application contains.
func TestTheApplicationIntegrationHasOneCompositionFile(t *testing.T) {
	t.Parallel()

	root := packageRoot(t)
	guides := []string{
		"README.md",
		".agents/skills/ticket-package/SKILL.md",
	}
	bootstrapFile := regexp.MustCompile(`bootstrap/[A-Za-z0-9_.-]+\.go`)

	for _, guide := range guides {
		body, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(guide)))
		if err != nil {
			t.Fatalf("reading %s: %v", guide, err)
		}

		text := string(body)
		for _, required := range []string{"bootstrap/app.go", "ticket.New(", "k.Register", "AccountResolver", "Notifier", "aru migrate"} {
			if !strings.Contains(text, required) {
				t.Errorf("%s no longer teaches the explicit composition step %q", guide, required)
			}
		}

		for _, referenced := range bootstrapFile.FindAllString(text, -1) {
			if referenced != "bootstrap/app.go" {
				t.Errorf("%s introduces a second composition file %s", guide, referenced)
			}
		}
	}
}

// TestThePackageHasOneOwnerPerResponsibility freezes the application shapes
// this package is allowed to introduce, including one Service owner for Model
// access per side and no parallel composition abstraction.
func TestThePackageHasOneOwnerPerResponsibility(t *testing.T) {
	t.Parallel()

	root := packageRoot(t)
	forbiddenPaths := []string{
		"app/Actions",
		"app/Data",
		"app/Rules",
		"app/Support",
		"bootstrap/providers.go",
		"routes/api.go",
		"routes/channels.go",
		"public/assets/manifest",
		"public/assets/manifest.json",
		"repository.go",
		"configure.go",
	}

	for _, path := range forbiddenPaths {
		if _, err := os.Lstat(filepath.Join(root, filepath.FromSlash(path))); err == nil {
			t.Errorf("refused application path %s exists in the package", path)
		} else if !os.IsNotExist(err) {
			t.Errorf("checking refused application path %s: %v", path, err)
		}
	}

	inspectExplicitComposition(t, root)
}

// The spellings of the generic model layer, in halves so this file does not
// carry them whole. Hesape removed that layer, and an entity written against it
// does not compile -- but a guide that teaches it does, and so does a comment
// that a configured copy would read as the way to write the next entity.
const (
	genericOpen      = "["
	genericModel     = "model.Model" + genericOpen
	genericBuilder   = "model.Builder" + genericOpen
	genericRows      = "model.Collection" + genericOpen
	genericFactory   = "Factory" + genericOpen
	genericNewModel  = "model.NewModel" + genericOpen
	genericInstance  = "NewInstance" + "("
	generatedHeading = "// Code generated by aru model:build" + " from model.go. DO NOT EDIT."
)

// TestThePackageUsesTheGeneratedConcreteModel freezes the package shape: every
// entity embeds the non-generic Model, its table is declared once beside it,
// the query aru model:build generates is the one way in, the entity keeps a
// custom block for its own rules, the Services own the database handle, and
// CRUD does not grow a Repository layer of its own.
func TestThePackageUsesTheGeneratedConcreteModel(t *testing.T) {
	t.Parallel()

	root := packageRoot(t)
	wants := map[string][]string{
		"model.go": {
			`"github.com/arandu-io/hesape/database/model"`,
			"type Ticket struct {\n\tmodel.Model\n",
			"type Message struct {\n\tmodel.Model\n",
			"type Attachment struct {\n\tmodel.Model\n",
			"var ticketTable = model.NewTable(model.TableSpec{",
			"ManualKey:    true,",
			"// arandu:begin custom\n",
			"// arandu:end custom\n",
		},
		"TicketQuery.go": {
			generatedHeading,
			"func Tickets(db model.DB) *TicketQuery",
			"type TicketCollection []*Ticket",
		},
		"MessageQuery.go":                  {generatedHeading, "func Messages(db model.DB) *MessageQuery"},
		"AttachmentQuery.go":               {generatedHeading, "func Attachments(db model.DB) *AttachmentQuery"},
		"CounterQuery.go":                  {generatedHeading, "func Counters(db model.DB) *CounterQuery"},
		"internal/platform/TicketQuery.go": {generatedHeading, "func Tickets(db model.DB) *TicketQuery"},
		"internal/platform/model.go":       {"Global:       true,", "NoTimestamps: true,"},
		"service.go": {
			"db     *data.DB",
			"func NewTicketService(db *data.DB, cfg Config) *TicketService",
			"Tickets(s.db).WhereKey(",
		},
		"team.go": {
			"func NewTeamService(db *data.DB, cfg Config) *TeamService",
			"platform.Tickets(s.db)",
		},
		"module.go": {
			"NewTicketService(db, cfg)",
			"NewTeamService(db, cfg)",
		},
	}
	for path, required := range wants {
		body, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(path)))
		if err != nil {
			t.Fatalf("reading %s: %v", path, err)
		}
		for _, want := range required {
			if !strings.Contains(string(body), want) {
				t.Errorf("%s does not contain %q", path, want)
			}
		}
	}

	// Every Go file, tests included, because a test written against the generic
	// layer is the example the next test is copied from.
	generated := map[string]bool{
		"TicketQuery.go": true, "MessageQuery.go": true, "AttachmentQuery.go": true, "CounterQuery.go": true,
		"internal/platform/TicketQuery.go": true,
	}
	err := filepath.WalkDir(root, func(path string, entry os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() && (entry.Name() == ".git" || entry.Name() == "testdata" || entry.Name() == "storage") {
			return filepath.SkipDir
		}
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			return nil
		}
		body, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		relative, err := filepath.Rel(root, path)
		if err != nil {
			return err
		}
		relative = filepath.ToSlash(relative)
		for _, stale := range []string{genericModel, genericBuilder, genericRows, genericFactory, genericNewModel, genericInstance} {
			if strings.Contains(string(body), stale) {
				t.Errorf("%s still spells the generic model layer %q", relative, stale)
			}
		}
		if !generated[relative] && strings.Contains(string(body), generatedHeading) {
			t.Errorf("%s carries the heading of a generated query, which only the generated files may", relative)
		}
		return nil
	})
	if err != nil {
		t.Fatalf("reading the Go files: %v", err)
	}
}

// TestTheGuidesTeachTheShapeOfThePackage keeps the local instructions teaching
// what the package is: the generated query, the Service boundary, the two
// sides, and the three places a Grant is issued without a customer.
